"""Generate src/tokenizers/bert_tables.mojo: what BertNormalizer and BertPreTokenizer need from the Unicode database.

    gen_bert.py OUT.mojo        (run with the oracle python, .venv/bin/python: its Unicode version is the reference)

CONTROL: Cc Cf Co (Cn is kept, as the crate keeps it; minus tab, newline, return), removed by clean_text. PUNCT: ASCII punctuation and P*, isolated by the
pre-tokenizer. MARKS: Mn, dropped by strip_accents. STRIP: code point -> its canonical decomposition without the marks
(strip_accents is NFD then drop Mn; Hangul syllables are decomposed in code). LOWER: code point -> str.lower() of it,
per code point as Rust's char::to_lowercase does; STRIPLOWER: both, in that order. SPACE: White_Space; CJK: BertNormalizer's ranges. Ranges are 12 hex digits each, maps are `cp=cp,cp;` in hex."""
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp < 0xE000) and pred(chr(cp))
        if ok and start is None: start = cp
        elif not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return "".join("%06x%06x" % r for r in out), len(out)

def table(f):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000 or 0xAC00 <= cp <= 0xD7A3: continue
        r = f(chr(cp))
        if r != chr(cp): out.append("%x=%s;" % (cp, ",".join("%x" % ord(c) for c in r)))
    return "".join(out), len(out)

cat = unicodedata.category
control = ranges(lambda c: cat(c) in ("Cc", "Cf", "Co") and c not in "\t\n\r")
punct = ranges(lambda c: (c.isascii() and not c.isalnum() and 33 <= ord(c) <= 126) or cat(c).startswith("P"))
marks = ranges(lambda c: cat(c) == "Mn")
strip = lambda c: "".join(x for x in unicodedata.normalize("NFD", c) if cat(x) != "Mn") if cat(c) != "Mn" else c
space = "".join("%06x%06x" % r for r in [(9, 13), (32, 32), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)])
cjk = "".join("%06x%06x" % r for r in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2A6DF), (0x2A700, 0x2B81F), (0x2B820, 0x2CEAF), (0x2F800, 0x2FA1F)])
decomp = table(strip)
lower = table(lambda c: c.lower())
striplow = table(lambda c: "".join(x.lower() for x in strip(c)))
with open(sys.argv[1], "w") as f:
    f.write(f"""# Generated by tools/gen_bert.py. Do not edit by hand; rerun the generator.
# source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}: {control[1]} control, {punct[1]} punctuation, {marks[1]} mark ranges; {decomp[1]} strip, {lower[1]} lowercase, {striplow[1]} strip+lowercase maps.
comptime CONTROL = "{control[0]}"
comptime PUNCT = "{punct[0]}"
comptime MARKS = "{marks[0]}"
comptime SPACE = "{space}"
comptime CJK = "{cjk}"
comptime STRIP = "{decomp[0]}"
comptime LOWER = "{lower[0]}"
comptime STRIPLOWER = "{striplow[0]}"
""")
